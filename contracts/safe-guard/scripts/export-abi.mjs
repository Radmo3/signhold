#!/usr/bin/env node
// Regenerates src/abi.ts from the compiled artifact. Run after `hardhat compile`; the test
// suite asserts the committed ABI matches the artifact so the two cannot drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "artifacts/contracts/SignholdGuard.sol/SignholdGuard.json"), "utf8"));
const out = `// GENERATED by scripts/export-abi.mjs from artifacts/contracts/SignholdGuard.sol/SignholdGuard.json. Do not edit.
export const SIGNHOLD_GUARD_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;

/** Creation bytecode of SignholdGuard (solc 0.8.28, optimizer 1000 runs, evm cancun). */
export const SIGNHOLD_GUARD_BYTECODE = "${artifact.bytecode}" as const;
`;
writeFileSync(join(root, "src/abi.ts"), out);
console.log(`wrote src/abi.ts (${artifact.abi.length} ABI entries, ${(artifact.bytecode.length - 2) / 2} bytes of bytecode)`);
